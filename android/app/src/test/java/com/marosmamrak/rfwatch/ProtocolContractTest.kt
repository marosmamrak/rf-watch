package com.marosmamrak.rfwatch

import com.marosmamrak.rfwatch.model.Band
import com.marosmamrak.rfwatch.model.Frame
import com.marosmamrak.rfwatch.model.Hello
import com.marosmamrak.rfwatch.model.Protocol
import com.marosmamrak.rfwatch.model.Track
import com.marosmamrak.rfwatch.model.droneDetected
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The node's own sample messages (the JSON files in `protocol/`, generated by the Rust tests from
 * `src/protocol.rs`) must parse into the expected model, so a server change that breaks
 * this client fails here instead of on a device.
 */
class ProtocolContractTest {

    @Test
    fun parsesTheNodesHello() {
        val hello = Protocol.parse(Fixtures.resource("hello.json")) as Hello
        assertEquals("rf-watch", hello.device)
        assertEquals(Band(startMhz = 2400f, stopMhz = 2483.5f, bins = 256, fps = 10), hello.band)
    }

    @Test
    fun parsesTheNodesFrame() {
        val frame = Protocol.parse(Fixtures.resource("frame.json")) as Frame
        assertEquals(812L, frame.seq)
        assertEquals(81_200L, frame.tMs)
        assertEquals(-96.8f, frame.noiseFloorDbm)
        assertEquals(-86.8f, frame.thresholdDbm)

        val (link, wifi) = frame.tracks
        val expected = Track(
            id = 3,
            kind = Track.KIND_FHSS_CONTROL,
            centerMhz = 2441.8f,
            bandwidthMhz = 72f,
            peakDbm = -61.2f,
            confidence = 0.9f,
            firstSeenMs = 10_100,
            lastSeenMs = 81_200,
            active = true,
        )
        assertEquals(expected, link)
        assertTrue(link.isDroneLink)
        assertEquals(Track.KIND_WIDEBAND, wifi.kind)
        assertFalse(wifi.active)
        assertTrue(droneDetected(frame.tracks))
    }

    @Test
    fun handWrittenFixturesKeepTheNodesKeys() {
        fun keys(json: String) = Json.parseToJsonElement(json).jsonObject.keys
        val nodeFrame = Json.parseToJsonElement(Fixtures.resource("frame.json")).jsonObject
        val nodeTrack = nodeFrame.getValue("tracks").jsonArray.first().jsonObject
        assertEquals(nodeFrame.keys, keys(Fixtures.frame(1)))
        assertEquals(nodeTrack.keys, keys(Fixtures.trackJson(1, Track.KIND_WIDEBAND, active = true)))
    }
}
